// Pixel comparisons. Excluded on CI (fonts rasterize differently on Linux).
//   flutter test --tags golden                     run locally
//   flutter test --tags golden --update-goldens    regenerate after a design change
//
// The style catalog: every recipe in assets/styles/recipes.json, rendered
// with a sample of the first category its family suits, saved as
// docs/design/catalog/<recipe name>.png (540x1200, Turkish, 10 Nov 2026).
@Tags(['golden'])
library;

import 'dart:io';

import 'package:dailywall/rendering/wallpaper_renderer.dart';
import 'package:flutter_test/flutter_test.dart';

import '../helpers/samples.dart';
import 'test_fonts.dart';

const catalogDir = 'docs/design/catalog';

void main() {
  setUpAll(loadAppFonts);
  final book = loadStyleBook();

  for (final recipe in book.recipes) {
    testWidgets('catalog ${recipe.name}', (tester) async {
      final content = sampleFor(recipe.family.fits.first);
      final image = await tester.runAsync(() async {
        final r = await WallpaperRenderer.render(
          content: content,
          recipe: recipe,
          width: 540,
          height: 1200,
        );
        return r.image;
      });
      await expectLater(
        image!,
        matchesGoldenFile('../../$catalogDir/${recipe.name}.png'),
      );
      image.dispose();
    });
  }

  test('catalog index lists every recipe', () {
    final index = StringBuffer()
      ..writeln('# Style catalog')
      ..writeln()
      ..writeln(
        'Generated by `flutter test --tags golden --update-goldens` '
        '(test/rendering/golden_test.dart). One image per recipe in '
        '`assets/styles/recipes.json`; the file name is the recipe name.',
      )
      ..writeln()
      ..writeln(
        '${book.recipes.length} recipes in ${book.families.length} families.',
      );
    for (final f in book.families) {
      index
        ..writeln()
        ..writeln('## ${f.name('en')} / ${f.name('tr')}')
        ..writeln()
        ..writeln('Suits: ${f.fits.join(', ')}')
        ..writeln();
      final recipes = book.ofFamily(f.id);
      index
        ..writeln('| ${[for (final r in recipes) r.name].join(' | ')} |')
        ..writeln('|${' --- |' * recipes.length}')
        ..writeln(
          '| ${[for (final r in recipes) '<img src="${r.name}.png" width="160">'].join(' | ')} |',
        );
    }
    final file = File('$catalogDir/README.md');
    if (autoUpdateGoldenFiles) {
      file
        ..createSync(recursive: true)
        ..writeAsStringSync(index.toString());
    }
    expect(file.readAsStringSync(), index.toString());
  });

  testWidgets('shared image watermark', (tester) async {
    final image = await tester.runAsync(() async {
      final r = await WallpaperRenderer.render(
        content: sampleFor('software_tips'),
        recipe: book.byName('terminal_amber')!,
        width: 540,
        height: 1200,
      );
      return WallpaperRenderer.withWatermark(r.image, 'dailywall');
    });
    await expectLater(
      image!,
      matchesGoldenFile('goldens/shared_watermark.png'),
    );
  });
}
